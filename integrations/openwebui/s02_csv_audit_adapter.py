"""
title: S02 CRM CSV Audit Adapter
description: Audit attached CRM CSV files using the local S02 FastAPI service.
"""
import io
import json
import urllib.request
import urllib.error
import uuid
import zipfile
from pathlib import Path

class Tools:
    def run_s02_csv_audit(self, __files__: list = None) -> str:
        """Audit attached contacts.csv and deals.csv files using deterministic S02 rules."""
        selected = {}
        for item in (__files__ or []):
            name = (item.get("name") or "").lower()
            metadata = item.get("file") or {}
            path_value = metadata.get("path")
            if name in ("contacts.csv", "deals.csv") and path_value:
                selected[name] = Path(path_value)
        missing = [name for name in ("contacts.csv", "deals.csv") if name not in selected]
        if missing:
            return json.dumps({"status": "error", "message": "Missing required CSV attachments", "missing": missing})
        boundary = uuid.uuid4().hex
        body = bytearray()
        for field, filename in (("contacts", "contacts.csv"), ("deals", "deals.csv")):
            path = selected[filename]
            if not path.is_file():
                return json.dumps({"status": "error", "message": f"File not found: {filename}"})
            data = path.read_bytes()
            body.extend((f"--{boundary}\r\n"
                         f'Content-Disposition: form-data; name="{field}"; filename="{filename}"\r\n'
                         "Content-Type: text/csv\r\n\r\n").encode("utf-8"))
            body.extend(data)
            body.extend(b"\r\n")
        body.extend(f"--{boundary}--\r\n".encode("utf-8"))
        request = urllib.request.Request(
            "http://host.containers.internal:8000/audit",
            data=bytes(body),
            headers={"Content-Type": f"multipart/form-data; boundary={boundary}"},
            method="POST",
        )
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                archive_bytes = response.read()
                http_status = response.status
            with zipfile.ZipFile(io.BytesIO(archive_bytes)) as archive:
                filenames = archive.namelist()
                for required in ("summary.json", "report.md"):
                    if required not in filenames:
                        return json.dumps({"status": "error", "message": f"Audit ZIP is missing {required}", "archive_files": filenames})
                summary = json.loads(archive.read("summary.json").decode("utf-8"))
                report = archive.read("report.md").decode("utf-8")
            return json.dumps({
                "status": "success", "http_status": http_status,
                "summary": summary, "report": report, "archive_files": filenames,
                "note": "These findings were generated by the deterministic S02 FastAPI auditor, not by the AI model.",
            }, ensure_ascii=False)
        except urllib.error.HTTPError as error:
            return json.dumps({"status": "error", "http_status": error.code,
                               "message": error.read().decode("utf-8", errors="replace")[:1000]})
        except zipfile.BadZipFile:
            return json.dumps({"status": "error", "message": "FastAPI returned an invalid ZIP archive."})
        except Exception as error:
            return json.dumps({"status": "error", "message": f"{type(error).__name__}: {error}"})
